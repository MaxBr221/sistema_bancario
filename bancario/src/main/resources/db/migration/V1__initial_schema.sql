-- =========================================================
-- 1. CLIENTE
-- =========================================================

CREATE TABLE cliente (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_completo VARCHAR(255) NOT NULL,
    cpf VARCHAR(255) NOT NULL UNIQUE,
    telefone VARCHAR(255) NOT NULL,
    data_nascimento DATE NOT NULL,
    status_conta VARCHAR(255) NOT NULL,
    criado_em TIMESTAMP NOT NULL,
    login VARCHAR(255) NOT NULL,
    senha VARCHAR(255) NOT NULL,

    CONSTRAINT chk_cliente_status
        CHECK (status_conta IN ('ATIVA', 'BLOQUEADA', 'ENCERRADA'))
);


-- =========================================================
-- 2. CREDENCIAL
-- =========================================================

CREATE TABLE credenciais (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL UNIQUE,
    email_login VARCHAR(150) NOT NULL UNIQUE,
    senha_hash VARCHAR(255) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMP NOT NULL,
    atualizado_em TIMESTAMP,

    CONSTRAINT fk_credencial_cliente
        FOREIGN KEY (cliente_id)
        REFERENCES cliente(id)
        ON DELETE RESTRICT
);


-- =========================================================
-- 3. USUÁRIO ADMINISTRADOR
-- =========================================================

CREATE TABLE usuarios_admin (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    senha_hash VARCHAR(255) NOT NULL,
    perfil VARCHAR(30) NOT NULL DEFAULT 'ADMIN',
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMP NOT NULL,
    atualizado_em TIMESTAMP
);


-- =========================================================
-- 4. CONTA BANCÁRIA
-- =========================================================

CREATE TABLE contas_bancarias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL,
    agencia VARCHAR(10) NOT NULL UNIQUE,
    numero VARCHAR(20) NOT NULL UNIQUE,
    tipo VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ATIVA',
    versao BIGINT NOT NULL DEFAULT 0,
    saldo NUMERIC(19,2) NOT NULL DEFAULT 0.00,
    criada_em TIMESTAMP NOT NULL,

    CONSTRAINT fk_conta_cliente
        FOREIGN KEY (cliente_id)
        REFERENCES cliente(id)
        ON DELETE RESTRICT,

    CONSTRAINT chk_conta_tipo
        CHECK (tipo IN ('CORRENTE', 'POUPANCA')),

    CONSTRAINT chk_conta_status
        CHECK (status IN ('ATIVA', 'BLOQUEADA', 'ENCERRADA')),

    CONSTRAINT chk_conta_saldo
        CHECK (saldo >= 0)
);


-- =========================================================
-- 5. CONTA CONTÁBIL
-- =========================================================

CREATE TABLE contas_contabeis (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(30) NOT NULL UNIQUE,
    nome VARCHAR(120) NOT NULL,
    tipo VARCHAR(30) NOT NULL,
    ativa BOOLEAN NOT NULL DEFAULT TRUE
);


-- =========================================================
-- 6. LIMITE OPERACIONAL
-- =========================================================

CREATE TABLE limites_operacionais (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conta_id BIGINT NOT NULL UNIQUE,
    limite_saque_diario NUMERIC(19,2) NOT NULL DEFAULT 1000.00,
    limite_transferencia_diaria NUMERIC(19,2) NOT NULL DEFAULT 5000.00,
    limite_por_transferencia NUMERIC(19,2) NOT NULL DEFAULT 2000.00,
    atualizado_em TIMESTAMP NOT NULL,

    CONSTRAINT fk_limite_conta
        FOREIGN KEY (conta_id)
        REFERENCES contas_bancarias(id)
        ON DELETE RESTRICT,

    CONSTRAINT chk_limite_saque
        CHECK (limite_saque_diario >= 0),

    CONSTRAINT chk_limite_transferencia_diaria
        CHECK (limite_transferencia_diaria >= 0),

    CONSTRAINT chk_limite_por_transferencia
        CHECK (limite_por_transferencia >= 0)
);


-- =========================================================
-- 7. TRANSAÇÃO
-- =========================================================

CREATE TABLE transacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo VARCHAR(20) NOT NULL,
    valor NUMERIC(19,2) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDENTE',
    conta_origem_id BIGINT,
    conta_destino_id BIGINT,
    criada_em TIMESTAMP NOT NULL,
    concluida_em TIMESTAMP,

    CONSTRAINT fk_transacao_conta_origem
        FOREIGN KEY (conta_origem_id)
        REFERENCES contas_bancarias(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_transacao_conta_destino
        FOREIGN KEY (conta_destino_id)
        REFERENCES contas_bancarias(id)
        ON DELETE RESTRICT,

    CONSTRAINT chk_transacao_tipo
        CHECK (tipo IN ('DEPOSITO', 'SAQUE', 'TRANSFERENCIA')),

    CONSTRAINT chk_transacao_status
        CHECK (status IN (
            'PENDENTE',
            'CONCLUIDA',
            'FALHOU',
            'ESTORNADA'
        )),

    CONSTRAINT chk_transacao_valor
        CHECK (valor > 0),

    CONSTRAINT chk_transacao_contas
        CHECK (
            (
                tipo = 'DEPOSITO'
                AND conta_origem_id IS NULL
                AND conta_destino_id IS NOT NULL
            )
            OR
            (
                tipo = 'SAQUE'
                AND conta_origem_id IS NOT NULL
                AND conta_destino_id IS NULL
            )
            OR
            (
                tipo = 'TRANSFERENCIA'
                AND conta_origem_id IS NOT NULL
                AND conta_destino_id IS NOT NULL
                AND conta_origem_id <> conta_destino_id
            )
        )
);


-- =========================================================
-- 8. LANÇAMENTO CONTÁBIL
-- =========================================================

CREATE TABLE lancamentos_contabeis (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transacao_id BIGINT NOT NULL,
    conta_contabil_id BIGINT NOT NULL,
    natureza VARCHAR(10) NOT NULL,
    valor NUMERIC(19,2) NOT NULL,
    criado_em TIMESTAMP NOT NULL,

    CONSTRAINT fk_lancamento_transacao
        FOREIGN KEY (transacao_id)
        REFERENCES transacoes(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_lancamento_conta_contabil
        FOREIGN KEY (conta_contabil_id)
        REFERENCES contas_contabeis(id)
        ON DELETE RESTRICT,

    CONSTRAINT chk_lancamento_natureza
        CHECK (natureza IN ('DEBITO', 'CREDITO')),

    CONSTRAINT chk_lancamento_valor
        CHECK (valor > 0)
);


-- =========================================================
-- 9. CHAVE DE IDEMPOTÊNCIA
-- =========================================================

CREATE TABLE chaves_idempotencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    escopo VARCHAR(100) NOT NULL,
    chave VARCHAR(100) NOT NULL,
    hash_requisicao VARCHAR(64) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDENTE',
    transacao_id BIGINT UNIQUE,
    criada_em TIMESTAMP NOT NULL,
    expira_em TIMESTAMP,

    CONSTRAINT uk_idempotencia_usuario_chave
        UNIQUE (escopo, chave),

    CONSTRAINT fk_idempotencia_transacao
        FOREIGN KEY (transacao_id)
        REFERENCES transacoes(id)
        ON DELETE RESTRICT,

    CONSTRAINT chk_idempotencia_status
        CHECK (status IN (
            'PENDENTE',
            'CONCLUIDA',
            'FALHOU',
            'ESTORNADA'
        ))
);


-- =========================================================
-- 10. ÍNDICES
-- =========================================================

CREATE INDEX idx_contas_bancarias_cliente
    ON contas_bancarias(cliente_id);

CREATE INDEX idx_transacoes_conta_origem
    ON transacoes(conta_origem_id);

CREATE INDEX idx_transacoes_conta_destino
    ON transacoes(conta_destino_id);

CREATE INDEX idx_transacoes_criada_em
    ON transacoes(criada_em);

CREATE INDEX idx_transacoes_status
    ON transacoes(status);

CREATE INDEX idx_lancamentos_transacao
    ON lancamentos_contabeis(transacao_id);

CREATE INDEX idx_lancamentos_conta_contabil
    ON lancamentos_contabeis(conta_contabil_id);

CREATE INDEX idx_chaves_idempotencia_expiracao
    ON chaves_idempotencia(expira_em);


